export interface TlsCipher {
  name: string;
  standardName: string;
  version: 'TLSv1.2' | 'TLSv1.3';
}

export function cipherOf(id: number, version: TlsCipher['version']): TlsCipher {
  const known = SUITES.find(([n]) => n === id);
  const hex = `0x${id.toString(16).padStart(4, '0').toUpperCase()}`;
  return { name: known?.[1] ?? hex, standardName: known?.[2] ?? hex, version };
}
